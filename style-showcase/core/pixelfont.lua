  [":"] = { "...", ".#.", "...", ".#.", "..." }, ["-"] = { "...", "...", "###", "...", "..." },
  [" "] = { "...", "...", "...", "...", "..." },
}

-- Build an ImageFont: glyphs side by side, separated by a 1px column of a marker colour.
function pixelfont.make()
  local order = "ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789.!:- "
  local w = 1 + #order * 4
  local d = love.image.newImageData(w, 5)
  local x = 0
  for i = 1, #order do
    for y = 0, 4 do d:setPixel(x, y, 1, 0, 1, 1) end -- separator
    x = x + 1
    local g = FONT[order:sub(i, i)]
    for y = 1, 5 do
      for gx = 1, 3 do
        if g[y]:sub(gx, gx) == "#" then d:setPixel(x + gx - 1, y - 1, 1, 1, 1, 1) end
      end
    end
    x = x + 3
  end
  for y = 0, 4 do d:setPixel(x, y, 1, 0, 1, 1) end
  local f = lg.newImageFont(d, order, 1)
  f:setFilter("nearest", "nearest")
  return f
end

return pixelfont
